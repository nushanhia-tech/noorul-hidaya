import { Bell } from "lucide-react";
import { createClient } from "@/lib/supabase/server";
import { requireUser } from "@/lib/auth/session";
import { PageHeader, EmptyState, Pagination } from "@/components/ui/misc";
import { Card } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { formatDateTime, humanize } from "@/lib/format";
import { markAllNotificationsRead } from "@/app/portal/notifications-actions";
import { cn } from "@/lib/utils";

const PAGE = 25;

export async function NotificationsPage({ searchParams, base }: { searchParams: Promise<{ page?: string; filter?: string }>; base: string }) {
  const user = await requireUser();
  const sp = await searchParams;
  const page = Math.max(1, Number(sp.page) || 1);
  const supabase = await createClient();
  let q = supabase.from("notifications").select("*", { count: "exact" }).eq("user_id", user.id).order("created_at", { ascending: false });
  if (sp.filter === "unread") q = q.is("read_at", null);
  const { data, count } = await q.range((page - 1) * PAGE, page * PAGE - 1);
  return (
    <>
      <PageHeader title="Notifications" description="Updates generated by activity on your records."
        actions={<form action={markAllNotificationsRead}><button className="h-9 rounded-sm border border-line-strong bg-paper px-3 text-sm hover:bg-white">Mark all as read</button></form>} />
      <div className="mb-4 flex gap-2 text-sm">
        <a href={`${base}/notifications`} className={cn("rounded-sm px-3 py-1.5", sp.filter !== "unread" ? "bg-ink text-white" : "bg-sand")}>All</a>
        <a href={`${base}/notifications?filter=unread`} className={cn("rounded-sm px-3 py-1.5", sp.filter === "unread" ? "bg-ink text-white" : "bg-sand")}>Unread</a>
      </div>
      <Card>
        {!data?.length ? <EmptyState icon={Bell} title="No notifications" description="You will be notified about results, fees, requests and assignments here." /> : (
          <ul className="divide-y divide-line">
            {data.map((n) => (
              <li key={n.id}>
                <a href={`/portal/notifications/${n.id}`} className={cn("flex gap-4 px-5 py-4 hover:bg-white", !n.read_at && "bg-accent-50/40")}>
                  <span className={cn("mt-2 h-2 w-2 shrink-0 rounded-full", n.read_at ? "bg-line" : "bg-accent")} />
                  <span className="min-w-0 flex-1">
                    <span className="flex flex-wrap items-center gap-2"><span className="font-medium">{n.title}</span><Badge>{humanize(n.type)}</Badge></span>
                    {n.body && <span className="mt-1 block text-sm text-muted">{n.body}</span>}
                    <span className="mt-1 block text-xs text-faint">{formatDateTime(n.created_at)}</span>
                  </span>
                </a>
              </li>
            ))}
          </ul>
        )}
        <Pagination page={page} pageSize={PAGE} total={count ?? 0} hrefFor={(p) => `${base}/notifications?page=${p}${sp.filter ? `&filter=${sp.filter}` : ""}`} />
      </Card>
    </>
  );
}
